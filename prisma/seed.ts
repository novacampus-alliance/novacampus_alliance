function t(hms: string): Date {
  return new Date(`1970-01-01T${hms}Z`);
}

function mapPaymentStatus(s: string): string {
  switch (s) {
    case 'Payé':       return 'paye';
    case 'Retard':     return 'en_retard';
    case 'En attente': return 'en_attente';
    default:           return 'en_attente';
  }
}

function mapEnrollmentStatus(s: string): string {
  switch (s) {
    case 'En cours':  return 'inscrit';
    case 'Validé':    return 'valide';
    case 'Abandonné': return 'abandonne';
    case 'Échec':     return 'echec';
    default:          return 'inscrit';
  }
}

