import { PrismaClient, Role } from '@prisma/client';
import * as bcrypt from 'bcrypt';

const prisma = new PrismaClient();

const passwordHashCache = new Map<string, string>();

function seedPassword(role: Role, firstName: string): string {
  switch (role) {
    case Role.ADMIN:
      return `Admin${firstName}2026!`;
    case Role.DIRECTION:
      return `Dir${firstName}2026!`;
    case Role.INSTRUCTOR:
      return `Prof${firstName}2026!`;
    case Role.STUDENT:
      return `Etu${firstName}2026!`;
    default:
      return `Nova${firstName}2026!`;
  }
}

async function hashPassword(plain: string): Promise<string> {
  const cached = passwordHashCache.get(plain);
  if (cached) return cached;
  const hash = await bcrypt.hash(plain, 10);
  passwordHashCache.set(plain, hash);
  return hash;
}

